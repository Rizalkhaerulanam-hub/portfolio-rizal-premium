-- 1. Buat tipe ENUM (aman jika sudah ada)
DO $$ BEGIN
    CREATE TYPE public.access_role AS ENUM ('NONE','FEMALE','MALE','PUBLIC');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE public.account_status AS ENUM ('PENDING','APPROVED','REJECTED','REVOKED');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE public.request_status AS ENUM ('PENDING','APPROVED','REJECTED');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 2. Buat tabel profiles, requests, dan photos
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text,
  access_role public.access_role NOT NULL DEFAULT 'NONE',
  status public.account_status NOT NULL DEFAULT 'PENDING',
  is_admin boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.access_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  applicant_name text NOT NULL,
  requested_role public.access_role NOT NULL,
  wa_number text NOT NULL,
  status public.request_status NOT NULL DEFAULT 'PENDING',
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  access_role public.access_role NOT NULL,
  display_url text NOT NULL,
  is_published boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.access_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.photos ENABLE ROW LEVEL SECURITY;

-- 4. Helper Function: cek status admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS(SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.is_admin = true);
$$;

-- 5. Kebijakan Keamanan (RLS Policies)
-- 5a. Profiles
DROP POLICY IF EXISTS "users read own profile" ON public.profiles;
CREATE POLICY "users read own profile" ON public.profiles
FOR SELECT TO authenticated USING (id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS "users update own pending profile name only" ON public.profiles;
CREATE POLICY "users update own pending profile name only" ON public.profiles
FOR UPDATE TO authenticated USING (id = auth.uid())
WITH CHECK (id = auth.uid());

DROP POLICY IF EXISTS "admins manage profiles" ON public.profiles;
CREATE POLICY "admins manage profiles" ON public.profiles
FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

-- 5b. Access Requests
DROP POLICY IF EXISTS "users create own access request" ON public.access_requests;
CREATE POLICY "users create own access request" ON public.access_requests
FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS "users read own requests" ON public.access_requests;
CREATE POLICY "users read own requests" ON public.access_requests
FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS "admins manage requests" ON public.access_requests;
CREATE POLICY "admins manage requests" ON public.access_requests
FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

-- 5c. Photos
DROP POLICY IF EXISTS "approved users read allowed photos" ON public.photos;
CREATE POLICY "approved users read allowed photos" ON public.photos
FOR SELECT TO authenticated
USING (
  public.is_admin()
  OR (
    is_published = true
    AND EXISTS(
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND p.status = 'APPROVED'
        AND (
          (p.access_role = 'PUBLIC' AND public.photos.access_role IN ('PUBLIC', 'MALE', 'FEMALE'))
          OR (p.access_role = 'MALE' AND public.photos.access_role IN ('PUBLIC', 'MALE'))
          OR (p.access_role = 'FEMALE' AND public.photos.access_role IN ('PUBLIC', 'FEMALE'))
        )
    )
  )
);

DROP POLICY IF EXISTS "admins manage photos" ON public.photos;
CREATE POLICY "admins manage photos" ON public.photos
FOR ALL TO authenticated
USING (public.is_admin()) WITH CHECK (public.is_admin());

-- 6. Trigger Otomatis saat user baru registrasi
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles(id) VALUES (new.id)
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

